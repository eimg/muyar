#!/usr/bin/env python3
"""Regenerate bundled marks and Swift mappings from the checked-in catalog.

Use --check for an offline consistency check. Source archives are fetched only
when regenerating and absent from build/ExpandedIconSources, then hash-verified.
"""
import argparse
import hashlib
import io
import json
from pathlib import Path
import re
import tarfile
import urllib.request
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parent.parent
CATALOG = ROOT / "ThirdParty/BrandIcons/catalog.json"
ASSETS = ROOT / "Muyar/Assets.xcassets"
SWIFT = ROOT / "Muyar/InstrumentBrand.swift"
TINTS = ["primary", "bitcoin", "ethereum", "nvidia", "positive", "red", "gold", "blue", "original"]


def validate(catalog):
    ids = set()
    symbols = {"stocks": set(), "crypto": set(), "reserved": set()}
    for icon in catalog["icons"]:
        assert re.fullmatch(r"[a-z][a-z0-9]*", icon["id"]), icon["id"]
        assert icon["id"] not in ids, f"Duplicate icon: {icon['id']}"
        ids.add(icon["id"])
        assert icon["tint"] in TINTS
        assert icon["source"] == "local" or icon["source"] in catalog["sources"]
        assert icon["market"] in symbols
        assert bool(icon["symbols"]) == (icon["market"] != "reserved")
        for symbol in icon["symbols"]:
            assert symbol and symbol == symbol.upper()
            assert symbol not in symbols[icon["market"]], f"Ambiguous symbol: {symbol}"
            symbols[icon["market"]].add(symbol)


def swift_source(icons):
    lines = [
        "// Generated by scripts/update-brand-icons.py. Edit ThirdParty/BrandIcons/catalog.json.",
        "import Foundation", "", "enum InstrumentBrand: String, CaseIterable, Identifiable, Sendable {",
    ]
    for start in range(0, len(icons), 5):
        lines.append("    case " + ", ".join(icon["id"] for icon in icons[start:start + 5]))
    lines += ["", "    enum Tint: Sendable { case " + ", ".join(TINTS) + " }",
              '    var id: String { rawValue }',
              '    var assetName: String { "Brand-\\(rawValue)" }',
              '    var tint: Tint { Self.tints[self] ?? .primary }', "",
              "    private static let tints: [Self: Tint] = ["]
    for icon in icons:
        if icon["tint"] != "primary":
            lines.append(f'        .{icon["id"]}: .{icon["tint"]},')
    lines += ["    ]", ""]
    for market in ["stocks", "crypto"]:
        lines.append(f"    static let {market}Symbols: [String: Self] = [")
        for icon in icons:
            if icon["market"] == market:
                for symbol in icon["symbols"]:
                    lines.append(f'        "{symbol}": .{icon["id"]},')
        lines += ["    ]", ""]
    lines += ["}", "", "extension Instrument {", "    var brand: InstrumentBrand? {",
              "        switch provider {", "        case .binance:",
              "            guard category == .crypto, !currency.isEmpty, symbol.hasSuffix(currency), symbol.count > currency.count else { return nil }",
              "            // Exact base assets only: BTCUP and ETHFI must not inherit BTC/ETH marks.",
              "            return InstrumentBrand.cryptoSymbols[String(symbol.dropLast(currency.count))]",
              "        case .yahoo:", "            guard category == .stocks else { return nil }",
              "            return InstrumentBrand.stocksSymbols[symbol]", "        }", "    }", "}", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    catalog = json.loads(CATALOG.read_text())
    validate(catalog)
    icons = catalog["icons"]
    generated = swift_source(icons)
    if args.check:
        assert SWIFT.read_text() == generated, "Swift mappings need regeneration"
    else:
        SWIFT.write_text(generated)
    archives = {}
    try:
        for icon in icons:
            folder = ASSETS / f'Brand-{icon["id"]}.imageset'
            svg = folder / f'{icon["id"]}.svg'
            manifest = {
                "images": [{"filename": svg.name, "idiom": "universal"}],
                "info": {"author": "xcode", "version": 1},
                "properties": {"preserves-vector-representation": True},
            }
            if icon["tint"] != "original":
                manifest["properties"]["template-rendering-intent"] = "template"
            if args.check:
                data = svg.read_bytes()
                assert json.loads((folder / "Contents.json").read_text()) == manifest, folder
            else:
                if icon["source"] == "local":
                    data = (CATALOG.parent / icon["path"]).read_bytes()
                else:
                    source_id = icon["source"]
                    source = catalog["sources"][source_id]
                    if source_id not in archives:
                        cache = ROOT / "build/ExpandedIconSources" / source["archive"]
                        if not cache.exists():
                            cache.parent.mkdir(parents=True, exist_ok=True)
                            with urllib.request.urlopen(source["url"], timeout=30) as response:
                                cache.write_bytes(response.read())
                        archive_data = cache.read_bytes()
                        assert hashlib.sha256(archive_data).hexdigest() == source["sha256"], source_id
                        archives[source_id] = tarfile.open(fileobj=io.BytesIO(archive_data), mode="r:gz")
                    data = archives[source_id].extractfile(icon["path"]).read()
                folder.mkdir(parents=True, exist_ok=True)
                svg.write_bytes(data)
                (folder / "Contents.json").write_text(json.dumps(manifest, indent=2) + "\n")
            assert hashlib.sha256(data).hexdigest() == icon["sha256"], icon["id"]
            document = ET.fromstring(data)
            assert document.tag.endswith("svg"), icon["id"]
            assert all(not node.tag.endswith(("script", "image", "foreignObject")) for node in document.iter())
            assert not any("href" in key for node in document.iter() for key in node.attrib)
        expected = {f'Brand-{icon["id"]}.imageset' for icon in icons}
        actual = {path.name for path in ASSETS.glob("Brand-*.imageset")}
        assert expected == actual, f"Unexpected/missing icon sets: {expected ^ actual}"
    finally:
        for archive in archives.values():
            archive.close()
    print(f'{len(icons)} icons verified: {sum(i["market"] == "stocks" for i in icons)} companies, {sum(i["market"] == "crypto" for i in icons)} crypto assets, {sum(i["market"] == "reserved" for i in icons)} reserved marks')


if __name__ == "__main__":
    main()
